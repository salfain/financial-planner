import { createHash, generateKeyPairSync } from "node:crypto";
import { chmod, mkdir, writeFile } from "node:fs/promises";
import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const keyDirectory = join(homedir(), ".financial-planner-license");
const privateKeyPath = join(keyDirectory, "private.pem");
const publicKeyPath = join(keyDirectory, "public.pem");

await mkdir(keyDirectory, { recursive: true, mode: 0o700 });
const { privateKey, publicKey } = generateKeyPairSync("rsa", {
  modulusLength: 2048,
  publicKeyEncoding: { type: "spki", format: "pem" },
  privateKeyEncoding: { type: "pkcs8", format: "pem" },
});
const jwk = await import("node:crypto").then(({ createPublicKey }) => createPublicKey(publicKey).export({ format: "jwk" }));
if (!jwk.n || !jwk.e) throw new Error("Public JWK RSA tidak lengkap.");
const fingerprint = createHash("sha256").update(publicKey).digest("hex");

await writeFile(privateKeyPath, privateKey, { mode: 0o600, flag: "wx" });
await writeFile(publicKeyPath, publicKey, { mode: 0o644, flag: "wx" });
await chmod(privateKeyPath, 0o600);

await writeFile(join(root, "lib", "license-public-key.ts"), `// Generated by scripts/generate-license-key.mjs. Do not edit manually.\nexport const LICENSE_PUBLIC_KEY = {\n  kty: "RSA",\n  n: "${jwk.n}",\n  e: "${jwk.e}",\n  alg: "RS256",\n  ext: true,\n  key_ops: ["verify"],\n} as const;\n\nexport const LICENSE_PUBLIC_KEY_FINGERPRINT = "${fingerprint}";\n`);
await writeFile(join(root, "apps-script", "LicensePublicKey.gs"), `// Generated by scripts/generate-license-key.mjs. Do not edit manually.\nconst FINANCIAL_PLANNER_LICENSE_PUBLIC_KEY = Object.freeze({\n  n: '${jwk.n}',\n  e: '${jwk.e}',\n  fingerprint: '${fingerprint}'\n});\n`);

console.log(`Private key: ${privateKeyPath}`);
console.log(`Public key: ${publicKeyPath}`);
console.log(`Fingerprint: ${fingerprint}`);
console.log("Simpan backup private key terenkripsi. Jangan kirim private.pem kepada pelanggan.");
