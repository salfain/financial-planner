import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "vite";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(scriptDirectory, "..");
const outputDirectory = join(projectRoot, "dist", "gas-frontend");
const appsScriptDirectory = join(projectRoot, "apps-script");

await build({
  configFile: join(projectRoot, "vite.gas.config.ts"),
});

const files = await readdir(outputDirectory);

function requireSingleAsset(extension) {
  const matches = files.filter((file) => file.endsWith(extension));
  if (matches.length !== 1) {
    throw new Error(
      `Build GAS mengharapkan tepat satu file ${extension}, ditemukan: ${matches.join(", ") || "tidak ada"}.`,
    );
  }
  return join(outputDirectory, matches[0]);
}

const [javascript, css] = await Promise.all([
  readFile(requireSingleAsset(".js"), "utf8"),
  readFile(requireSingleAsset(".css"), "utf8"),
]);

function makeLargeBase64LiteralsTemplateSafe(source) {
  return source.replace(/(["'])([A-Za-z0-9+/=]{16384,})\1/g, (_match, quote, value) =>
    Array.from({ length: Math.ceil(value.length / 8_192) }, (_unused, index) => {
      const chunk = value.slice(index * 8_192, (index + 1) * 8_192);
      // HtmlService's contextual parser can lose string context on very long
      // Base64 literals and treat `//` inside the data as a line comment.
      return `${quote}${chunk.replaceAll("/", "\\/")}${quote}`;
    }).join("+"),
  );
}

const safeJavascript = makeLargeBase64LiteralsTemplateSafe(javascript)
  // PowerPoint generators contain XML declarations such as `<?xml` inside
  // JavaScript string literals. HtmlService treats the raw `<?` token as a
  // template scriptlet even inside an included <script>. Hex escaping keeps
  // the JavaScript value identical at runtime without exposing that token to
  // the Apps Script template parser.
  .replaceAll("<?", "\\x3c?")
  .replace(/<\/script/gi, "<\\/script")
  // core-js ships a whitespace lookup as a multiline template literal. Escape
  // its trailing tab so the generated Apps Script bundle stays diff-clean.
  .replace(/(t\.exports=`)\t(?=\r?\n)/g, "$1\\t");
const safeCss = css.replace(/<\/style/gi, "<\\/style");

if (safeJavascript.includes("<?") || safeCss.includes("<?")) {
  throw new Error("Bundle mengandung token template Apps Script '<?' dan tidak aman untuk di-include.");
}
if (/<\/script/i.test(safeJavascript) || /<\/style/i.test(safeCss)) {
  throw new Error("Bundle masih mengandung tag penutup inline yang tidak aman.");
}
if (safeJavascript.includes("process.env.NODE_ENV")) {
  throw new Error("Bundle masih bergantung pada process.env.NODE_ENV dan tidak aman untuk browser Apps Script.");
}

const fingerprint = createHash("sha256")
  .update(safeJavascript)
  .update(safeCss)
  .digest("hex")
  .slice(0, 12);
const banner = `<!-- Generated by scripts/build-gas-frontend.mjs - ${fingerprint}. Do not edit directly. -->`;

await Promise.all([
  writeFile(
    join(appsScriptDirectory, "Frontend.html"),
    `${banner}\n<script>${safeJavascript}</script>\n`,
    "utf8",
  ),
  writeFile(
    join(appsScriptDirectory, "Styles.html"),
    `${banner}\n<style>${safeCss}</style>\n`,
    "utf8",
  ),
]);

console.log(`Apps Script frontend siap (${fingerprint}).`);
console.log("  apps-script/Styles.html");
console.log("  apps-script/Frontend.html");
